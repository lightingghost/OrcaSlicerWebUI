def create_test_stl_cube() -> bytes:
    """
    Create a minimal valid binary STL file representing a 10mm cube.
    
    Binary STL format:
    - 80 byte header
    - 4 bytes: number of triangles (uint32)
    - For each triangle:
      - 12 bytes: normal vector (3x float32)
      - 36 bytes: 3 vertices, each with x,y,z (9x float32)
      - 2 bytes: attribute byte count (uint16)
    
    A cube has 12 triangles (2 per face, 6 faces).
    """
    header = b"STL 10mm test cube for E2E smoke test" + b"\x00" * (80 - 38)
    
    # Define vertices for a 10mm cube (0 to 10mm in each axis)
    v = [
        (0.0, 0.0, 0.0),  # 0
        (10.0, 0.0, 0.0), # 1
        (10.0, 10.0, 0.0),# 2
        (0.0, 10.0, 0.0), # 3
        (0.0, 0.0, 10.0), # 4
        (10.0, 0.0, 10.0),# 5
        (10.0, 10.0, 10.0),# 6
        (0.0, 10.0, 10.0),# 7
    ]
    
    # Define 12 triangles (2 per face) with outward normals
    triangles = [
        # Bottom face (z=0, normal pointing down)
        ((v[0], v[2], v[1]), (0.0, 0.0, -1.0)),
        ((v[0], v[3], v[2]), (0.0, 0.0, -1.0)),
        # Top face (z=10, normal pointing up)
        ((v[4], v[5], v[6]), (0.0, 0.0, 1.0)),
        ((v[4], v[6], v[7]), (0.0, 0.0, 1.0)),
        # Front face (y=0, normal pointing forward)
        ((v[0], v[1], v[5]), (0.0, -1.0, 0.0)),
        ((v[0], v[5], v[4]), (0.0, -1.0, 0.0)),
        # Back face (y=10, normal pointing backward)
        ((v[3], v[7], v[6]), (0.0, 1.0, 0.0)),
        ((v[3], v[6], v[2]), (0.0, 1.0, 0.0)),
        # Left face (x=0, normal pointing left)
        ((v[0], v[4], v[7]), (-1.0, 0.0, 0.0)),
        ((v[0], v[7], v[3]), (-1.0, 0.0, 0.0)),
        # Right face (x=10, normal pointing right)
        ((v[1], v[2], v[6]), (1.0, 0.0, 0.0)),
        ((v[1], v[6], v[5]), (1.0, 0.0, 0.0)),
    ]
    
    # Pack triangle data
    triangle_data = b""
    for (v1, v2, v3), normal in triangles:
        # Normal vector (3x float32)
        triangle_data += struct.pack("<fff", *normal)
        # Vertex 1
        triangle_data += struct.pack("<fff", *v1)
        # Vertex 2
        triangle_data += struct.pack("<fff", *v2)
        # Vertex 3
        triangle_data += struct.pack("<fff", *v3)
        # Attribute byte count (uint16)
        triangle_data += struct.pack("<H", 0)
    
    # Assemble: header + triangle count + triangle data
    num_triangles = len(triangles)
    return header + struct.pack("<I", num_triangles) + triangle_data


