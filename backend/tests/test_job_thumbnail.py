class TestSpliceThumbnailIntoGcode:
    """Direct unit tests for the splicing helper itself."""

    def test_splices_after_header_block_end(self, tmp_path):
        gcode_path = tmp_path / "plate_1.gcode"
        gcode_path.write_text(
            "; HEADER_BLOCK_START\n; foo\n; HEADER_BLOCK_END\n\nG1 X0\n"
        )
        _splice_thumbnail_into_gcode(gcode_path, _TINY_PNG)

        text = gcode_path.read_text()
        assert text.index("; HEADER_BLOCK_END") < text.index("; THUMBNAIL_BLOCK_START")
        assert text.index("; THUMBNAIL_BLOCK_START") < text.index("G1 X0")

    def test_falls_back_to_prepend_when_no_header_block(self, tmp_path):
        """If a gcode file doesn't have a recognizable HEADER_BLOCK_END
        (unexpected shape), the thumbnail is still added rather than
        silently dropped — prepended to the top of the file."""
        gcode_path = tmp_path / "plate_1.gcode"
        gcode_path.write_text("G1 X0\n")
        _splice_thumbnail_into_gcode(gcode_path, _TINY_PNG)

        text = gcode_path.read_text()
        assert text.index("; THUMBNAIL_BLOCK_START") < text.index("G1 X0")

    def test_base64_payload_round_trips_to_original_png_bytes(self, tmp_path):
        """The base64 data embedded in the block, once line-unwrapped and
        decoded, reproduces the exact original PNG bytes — this is the
        actual native gcode-thumbnail-viewer contract."""
        import base64
        import re as re_module

        gcode_path = tmp_path / "plate_1.gcode"
        gcode_path.write_text("; HEADER_BLOCK_START\n; HEADER_BLOCK_END\n\nG1\n")
        _splice_thumbnail_into_gcode(gcode_path, _TINY_PNG)

        text = gcode_path.read_text()
        match = re_module.search(
            r"; thumbnail begin \d+x\d+ \d+\n(.*?)\n; thumbnail end",
            text,
            re_module.DOTALL,
        )
        assert match is not None
        b64_lines = [line[2:] for line in match.group(1).split("\n")]
        decoded = base64.b64decode("".join(b64_lines))
        assert decoded == _TINY_PNG

    def test_re_splicing_replaces_rather_than_duplicates(self, tmp_path):
        gcode_path = tmp_path / "plate_1.gcode"
        gcode_path.write_text("; HEADER_BLOCK_START\n; HEADER_BLOCK_END\n\nG1\n")
        _splice_thumbnail_into_gcode(gcode_path, _TINY_PNG)
        _splice_thumbnail_into_gcode(gcode_path, _TINY_PNG)

        text = gcode_path.read_text()
        assert text.count("; THUMBNAIL_BLOCK_START") == 1
        assert "G1" in text


