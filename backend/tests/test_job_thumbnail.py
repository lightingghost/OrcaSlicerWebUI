"""
Tests for POST /api/jobs/{job_id}/thumbnail.

Native OrcaSlicer's CLI has no way to generate a gcode thumbnail itself —
its `export_thumbnails_to_file` (libslic3r/GCode/Thumbnails.hpp) early-
returns whenever no thumbnail generator callback is registered, and the
CLI entry point (OrcaSlicer.cpp) never registers one (that only happens
in the desktop GUI's OpenGL-backed BackgroundSlicingProcess). This
endpoint lets the frontend upload a PNG it rendered itself (a snapshot of
the Prepare-tab's live Three.js viewport), registers it as a normal job
output file, AND splices it directly into the plate's .gcode as a
byte-for-byte equivalent of the `; THUMBNAIL_BLOCK_START ... ; thumbnail
begin WxH size ... ; thumbnail end ... ; THUMBNAIL_BLOCK_END` comment
block native's own GCode.cpp would have written — since that block is
pure ASCII comments, it can be spliced in after the fact without needing
the CLI to cooperate at all.

Requirements: (feature request) "Add png thumbnail when you slice the
stl to create gcode." / "since the thumbnail block is just a comment
block, can we insert a block of comment to the gcode with orca slicer
cli?"
"""

import json
from unittest.mock import AsyncMock, patch

import pytest
from fastapi.testclient import TestClient

from app.routers.jobs import _splice_thumbnail_into_gcode

# Minimal valid 1x1 PNG (smallest possible PNG file, magic bytes + IHDR/
# IDAT/IEND chunks for a 1x1 transparent pixel).
_TINY_PNG = bytes.fromhex(
    "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c489"
    "0000000a49444154789c6360000002000100ffff03000006000557bfabd4000000"
    "0049454e44ae426082"
)


def _init_app(job_row, tmp_output_dir=None):
    """Set up auth + a mocked DB whose `jobs` row is `job_row`, patching
    out the real database/cleanup-loop startup hooks so the app can be
    imported and driven via TestClient without a real SQLite file."""
    from app.auth import init_auth
    init_auth("test-secret-12345")

    from app.main import app
    from app.database import get_db

    async def mock_get_db():
        mock_db = AsyncMock()

        async def mock_execute(query, params=None, *args, **kwargs):
            cursor = AsyncMock()
            if query.strip().upper().startswith("SELECT"):
                cursor.fetchone = AsyncMock(return_value=job_row)
            return cursor

        mock_db.execute = mock_execute
        mock_db.commit = AsyncMock()
        yield mock_db

    app.dependency_overrides[get_db] = mock_get_db
    return app


def test_upload_thumbnail_success(tmp_path):
    """A valid PNG uploaded for a completed job is written to the job's
    output directory and registered as an output file, returning its
    summary (filename, size_bytes, download_url)."""
    output_dir = tmp_path / "output"
    output_dir.mkdir()

    job_row = {"status": "completed", "output_dir": str(output_dir)}

    with patch("app.database.init_db", new_callable=AsyncMock), \
         patch("app.cleanup.run_cleanup_loop", return_value=AsyncMock()):
        app = _init_app(job_row)
        try:
            client = TestClient(app)
            response = client.post(
                "/api/jobs/test-job-id/thumbnail",
                headers={
                    "Authorization": "Bearer test-secret-12345",
                    "Content-Type": "image/png",
                },
                content=_TINY_PNG,
            )

            assert response.status_code == 200
            data = response.json()
            assert data["filename"] == "thumbnail.png"
            assert data["size_bytes"] == len(_TINY_PNG)
            assert data["download_url"] == "/api/jobs/test-job-id/outputs/thumbnail.png"

            # File actually written to disk in the job's output directory.
            written = output_dir / "thumbnail.png"
            assert written.exists()
            assert written.read_bytes() == _TINY_PNG
        finally:
            app.dependency_overrides.clear()


def test_upload_thumbnail_splices_block_into_existing_gcode(tmp_path):
    """Uploading a thumbnail for a job that already produced a
    plate_N.gcode file splices the native-format comment block directly
    into that file, immediately after HEADER_BLOCK_END — matching where
    GCode.cpp's `_do_export` writes it for a real desktop-GUI slice."""
    output_dir = tmp_path / "output"
    output_dir.mkdir()
    gcode_path = output_dir / "plate_1.gcode"
    gcode_path.write_text(
        "; HEADER_BLOCK_START\n"
        "; generated by OrcaSlicer 2.4.2\n"
        "; HEADER_BLOCK_END\n\n"
        "; CONFIG_BLOCK_START\n"
        "; CONFIG_BLOCK_END\n\n"
        "G28\n"
    )
    job_row = {"status": "completed", "output_dir": str(output_dir)}

    with patch("app.database.init_db", new_callable=AsyncMock), \
         patch("app.cleanup.run_cleanup_loop", return_value=AsyncMock()):
        app = _init_app(job_row)
        try:
            client = TestClient(app)
            response = client.post(
                "/api/jobs/test-job-id/thumbnail",
                headers={"Authorization": "Bearer test-secret-12345"},
                content=_TINY_PNG,
            )
            assert response.status_code == 200

            text = gcode_path.read_text()
            assert "; THUMBNAIL_BLOCK_START" in text
            assert "; thumbnail begin 1x1" in text
            assert "; thumbnail end" in text
            assert "; THUMBNAIL_BLOCK_END" in text
            # Placed after the header block, before the rest of the file.
            header_idx = text.index("; HEADER_BLOCK_END")
            thumb_idx = text.index("; THUMBNAIL_BLOCK_START")
            gcode_idx = text.index("G28")
            assert header_idx < thumb_idx < gcode_idx
            # Original gcode content is preserved, not clobbered.
            assert "G28" in text
        finally:
            app.dependency_overrides.clear()


